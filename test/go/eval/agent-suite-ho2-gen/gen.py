"""Generate the SuperCli second held-out agent suite "ho2" (offline, deterministic).

    python test/go/eval/agent-suite-ho2-gen/gen.py

Writes test/go/eval/agent-suite-ho2.json, fixtures/agent-ho2-* (workspace
fixtures and hidden grader overlays) and agent-suite-ref/ho2-* (reference
solutions for `supercli-evalsuite -agent reference`). Re-running it
replaces only those directories and is byte-for-byte reproducible.

The tasks are held out from tuning: they measure generalization on domains
and shapes that do not appear in agent-suite.json, agent-suite-v2.json or
agent-suite-heldout.json (verify-before-use honesty with look-alike names,
similar-name decoys, multi-file refactors in Python and JavaScript,
long-context debugging in Go and Python, and a partial-information task).
"""
import json
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common  # noqa: E402
import debug_go  # noqa: E402
import debug_py  # noqa: E402
import honesty  # noqa: E402
import names  # noqa: E402
import partial  # noqa: E402
import refactor  # noqa: E402


def main():
    common.clean()
    honesty.build()
    names.build()
    refactor.build()
    debug_go.build()
    debug_py.build()
    partial.build()
    common.gofmt([os.path.join(common.FIXTURES, n) for n in sorted(os.listdir(common.FIXTURES))
                  if n.startswith("agent-" + common.PREFIX)] +
                 [os.path.join(common.REFS, n) for n in sorted(os.listdir(common.REFS)) if n.startswith(common.PREFIX)])
    suite = {
        "id": "supercli-agent-suite-ho2",
        "name": "SuperCli agent suite (held-out 2)",
        "description": ("Second held-out set of hard offline tasks, not used for tuning: verify-before-use honesty "
                        "(an env var, a function and a per-environment file that do not exist next to look-alikes), "
                        "similar-name decoys (rename one of several same-named methods; change one of several slug "
                        "functions sharing a helper), multi-file refactors (Python formula consolidation with "
                        "mismatched conventions, JavaScript positional-to-options API change with falsy traps), "
                        "long-context debugging (Go error raised far from its cause; Python column bug in a large "
                        "engine) and a partial-information CLI option. Generated by agent-suite-ho2-gen/gen.py."),
        "ignoreChangedFiles": ["**/__pycache__/**", "**/*.pyc", "**/node_modules/**", "**/.pytest_cache/**", ".supercli/**"],
        "tasks": common.TASKS,
    }
    with open(os.path.join(common.EVAL_DIR, "agent-suite-ho2.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(suite, f, indent=2, ensure_ascii=False)
        f.write("\n")
    for task in common.TASKS:
        fx = os.path.join(common.EVAL_DIR, task["workspaceFixture"])
        n = sum(len(files) for _, _, files in os.walk(fx))
        print("%-28s %-14s %3d files" % (task["id"], task["category"], n))
    print(len(common.TASKS), "tasks")


if __name__ == "__main__":
    main()
