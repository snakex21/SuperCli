"""Generate the SuperCli held-out agent suite (offline, deterministic).

    python test/go/eval/agent-suite-heldout-gen/gen.py

Writes test/go/eval/agent-suite-heldout.json, fixtures/agent-ho-* (workspace
fixtures and hidden grader overlays) and agent-suite-ref/ho-* (reference
solutions for `supercli-evalsuite -agent reference`). Re-running it
replaces only those directories and is byte-for-byte reproducible.

The tasks are kept out of everyday tuning: they measure generalization
(multi-file edits, partial-information honesty and long-context work) on
domains and shapes that do not appear in agent-suite.json or
agent-suite-v2.json.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common  # noqa: E402
import go_ctx  # noqa: E402
import honesty_tasks  # noqa: E402
import long_tasks  # noqa: E402
import py_rename  # noqa: E402
import ts_deprecate  # noqa: E402


def main():
    common.clean()
    py_rename.build()
    go_ctx.build()
    ts_deprecate.build()
    honesty_tasks.build()
    long_tasks.build()
    common.gofmt([os.path.join(common.FIXTURES, n) for n in os.listdir(common.FIXTURES) if n.startswith("agent-ho-")] +
                 [os.path.join(common.REFS, n) for n in os.listdir(common.REFS) if n.startswith("ho-")])
    suite = {
        "id": "supercli-agent-suite-heldout",
        "name": "SuperCli agent suite (held-out)",
        "description": ("Held-out hard offline tasks, not used for tuning: Python/Go/TypeScript multi-file edits "
                        "(rename with string keys and substring decoys, context.Context threading, rule-based batch "
                        "annotation), partial-information honesty (missing config key, function named differently) "
                        "and long-context work (exact report from a multi-file CSV ledger, eight-bug fix session "
                        "with a reduced context window). Generated by agent-suite-heldout-gen/gen.py."),
        "ignoreChangedFiles": ["**/__pycache__/**", "**/*.pyc", "**/node_modules/**", "**/.pytest_cache/**", ".supercli/**"],
        "tasks": common.TASKS,
    }
    with open(os.path.join(common.EVAL_DIR, "agent-suite-heldout.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(suite, f, indent=2, ensure_ascii=False)
        f.write("\n")
    for task in common.TASKS:
        fx = os.path.join(common.EVAL_DIR, task["workspaceFixture"])
        n = sum(len(files) for _, _, files in os.walk(fx))
        print("%-32s %3d files" % (task["id"], n))
    print(len(common.TASKS), "tasks")


if __name__ == "__main__":
    main()
