"""Generate the SuperCli third held-out agent suite "ho3" (offline, deterministic).

    python test/go/eval/agent-suite-ho3-gen/gen.py

Writes test/go/eval/agent-suite-ho3.json, fixtures/agent-ho3-* (workspace
fixtures and hidden grader overlays) and agent-suite-ref/ho3-* (solve.py
for ho3runner's reference mode, plus files/ + answer.md for the classic
`supercli-evalsuite -agent reference` where the task has no git setup).
Re-running it replaces only those directories and is byte-for-byte
reproducible. See README.md next to this file.
"""
import json
import os
import subprocess
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common  # noqa: E402
import t_data  # noqa: E402
import t_env  # noqa: E402
import t_git  # noqa: E402
import t_large  # noqa: E402
import t_multiturn  # noqa: E402
import t_polish  # noqa: E402
import t_polyglot  # noqa: E402
import t_windows  # noqa: E402


def gofmt_check():
    files = []
    for base, prefix in ((common.FIXTURES, "agent-" + common.PREFIX),):
        for name in sorted(os.listdir(base)):
            if name.startswith(prefix):
                for root, _, names in os.walk(os.path.join(base, name)):
                    files += [os.path.join(root, n) for n in sorted(names) if n.endswith(".go")]
    if files:
        out = subprocess.run(["gofmt", "-l"] + files, stdout=subprocess.PIPE, check=True).stdout.decode().strip()
        if out:
            raise SystemExit("not gofmt-clean:\n" + out)


def main():
    common.clean()
    t_multiturn.build()
    t_windows.build()
    t_git.build()
    t_large.build()
    t_polyglot.build()
    t_data.build()
    t_env.build()
    t_polish.build()
    gofmt_check()
    for task in common.TASK_OBJS:
        common.derive_classic_reference(task)
    suite = {
        "id": "supercli-agent-suite-ho3",
        "name": "SuperCli agent suite (held-out 3)",
        "description": ("Third held-out set, designed blind: multi-turn follow-ups (revert one change, corrected "
                        "spec), Windows specifics (Polish/space paths, CRLF + BOM byte preservation, paths beyond "
                        "MAX_PATH), git workflows (merge-conflict resolution on a new branch, a rebase question "
                        "that must leave history intact), exact call-site search in a 300+ file repo, a Go+TS+"
                        "Python schema change, do-not-touch constraints, exact CSV/JSON transformation, a "
                        "partially broken environment that must be reported honestly, and a Polish prompt that "
                        "needs a Polish answer. Run through test/go/eval/ho3runner (setup + multi-turn); "
                        "generated by agent-suite-ho3-gen/gen.py."),
        "ignoreChangedFiles": ["**/__pycache__/**", "**/*.pyc", "**/node_modules/**", "**/.pytest_cache/**",
                               ".supercli/**", ".ho3setup/**"],
        "tasks": common.TASKS,
    }
    suite_path = os.path.join(common.EVAL_DIR, "agent-suite-ho3.json")
    with open(suite_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(suite, f, indent=2, ensure_ascii=False)
        f.write("\n")
    gen_dir = os.path.dirname(os.path.abspath(__file__))
    extra = [os.path.relpath(suite_path, common.REPO).replace(os.sep, "/")]
    for n in sorted(os.listdir(gen_dir)):
        if n.endswith(".py") or n.endswith(".md"):
            extra.append(os.path.relpath(os.path.join(gen_dir, n), common.REPO).replace(os.sep, "/"))
    count, longest = common.assert_repo_hygiene(extra)
    for task in common.TASKS:
        fx = os.path.join(common.EVAL_DIR, task["workspaceFixture"])
        n = sum(len(files) for _, _, files in os.walk(fx))
        print("%-34s %-12s %4d files" % (task["id"], task["category"], n))
    print("%d tasks, %d generated files checked (not ignored, -text), longest repo path %d chars"
          % (len(common.TASKS), count, longest))


if __name__ == "__main__":
    main()
