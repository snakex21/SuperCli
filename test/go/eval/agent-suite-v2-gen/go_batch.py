def _padding(rng, pkg, n=14):
    out = []
    for i in range(n):
        a, b, c = rng.randint(2, 9), rng.randint(10, 99), rng.randint(3, 7)
        out.append(d('''
            // %(p)sHelper%(i)02d is an internal scoring helper kept for compatibility
            // with the v1 API. It maps x into a small bucket index.
            func %(p)sHelper%(i)02d(x int) int {
            	switch {
            	case x < 0:
            		return -%(a)d
            	case x %% %(c)d == 0:
            		return x/%(c)d + %(a)d
            	case x > %(b)d:
            		return %(b)d - x%%%(a)d
            	}
            	return x*%(a)d - %(c)d
            }
            ''' % {"p": pkg, "i": i, "a": a, "b": b, "c": c}))
    return "\n".join(out)


