"""Generate the SuperCli agent suite v2 (harder, offline, deterministic).

    python test/go/eval/agent-suite-v2-gen/gen.py

Writes test/go/eval/agent-suite-v2.json, fixtures/agent-v2-* (workspace
fixtures and hidden grader overlays) and agent-suite-ref/v2-* (reference
solutions for `supercli-evalsuite -agent reference`). Re-running it
replaces those directories and is byte-for-byte reproducible.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common  # noqa: E402
import go_batch  # noqa: E402
import go_more  # noqa: E402
import go_rename  # noqa: E402
import misc_tasks  # noqa: E402
import py_tasks  # noqa: E402
import ts_tasks  # noqa: E402


def main():
    common.clean()
    go_rename.build()
    go_more.build()
    go_batch.build()
    py_tasks.build()
    ts_tasks.build()
    misc_tasks.build()
    common.gofmt([os.path.join(common.FIXTURES, n) for n in os.listdir(common.FIXTURES) if n.startswith("agent-v2-")] +
          [os.path.join(common.REFS, n) for n in os.listdir(common.REFS) if n.startswith("v2-")])
    suite = {
        "id": "supercli-agent-suite-v2",
        "name": "SuperCli agent suite v2 (hard)",
        "description": ("Harder offline tasks on medium-size Go/Python/TypeScript repositories: multi-file refactors, "
                        "misleading-trace debugging, flaky tests, multi-file features, schema migration, long "
                        "compaction-forcing sessions, honesty variants, parallel reads, batched edits and "
                        "tool-output-heavy investigations. Generated by agent-suite-v2-gen/gen.py."),
        "ignoreChangedFiles": ["**/__pycache__/**", "**/*.pyc", "**/node_modules/**", "**/.pytest_cache/**", ".supercli/**"],
        "tasks": common.TASKS,
    }
    with open(os.path.join(common.EVAL_DIR, "agent-suite-v2.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(suite, f, indent=2, ensure_ascii=False)
        f.write("\n")
    for task in common.TASKS:
        fx = os.path.join(common.EVAL_DIR, task["workspaceFixture"])
        n = sum(len(files) for _, _, files in os.walk(fx))
        print("%-32s %3d files" % (task["id"], n))
    print(len(common.TASKS), "tasks")


if __name__ == "__main__":
    main()
