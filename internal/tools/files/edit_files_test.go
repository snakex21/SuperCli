package files

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, body := range files {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func readRel(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func runEditFiles(t *testing.T, root string, args map[string]any) Result {
	t.Helper()
	raw, _ := json.Marshal(args)
	res, err := NewEditFiles(root).Spec().Fn(context.Background(), raw)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func TestEditFilesPrependHeaderWithFilters(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"pkg/a/a.go":            "package a\r\n\r\nfunc A() {}\r\n",
		"pkg/a/a_test.go":       "package a\n",
		"pkg/b/gen.go":          "// Code generated by stringer; DO NOT EDIT.\n\npackage b\n",
		"pkg/b/licensed.go":     "// SPDX-License-Identifier: Apache-2.0\n\npackage b\n",
		"pkg/b/testdata/x.go":   "package x\n",
		"pkg/b/bom.go":          "\xEF\xBB\xBFpackage b\n",
		"cmd/main.go":           "package main\n",
		"pkg/b/notes.txt":       "not go\n",
		"pkg/node_modules/m.go": "package m\n",
	})
	res := runEditFiles(t, root, map[string]any{
		"include":         "pkg/**/*.go",
		"exclude":         "**/testdata/**",
		"action":          "prepend",
		"new":             "// SPDX-License-Identifier: MIT\n\n",
		"skip_if_matches": `SPDX-License-Identifier|^// Code generated .* DO NOT EDIT\.$`,
	})
	if res.Err != nil {
		t.Fatal(res.Err)
	}
	if got := readRel(t, root, "pkg/a/a.go"); got != "// SPDX-License-Identifier: MIT\r\n\r\npackage a\r\n\r\nfunc A() {}\r\n" {
		t.Fatalf("CRLF file: %q", got)
	}
	if got := readRel(t, root, "pkg/a/a_test.go"); got != "// SPDX-License-Identifier: MIT\n\npackage a\n" {
		t.Fatalf("LF file: %q", got)
	}
	if got := readRel(t, root, "pkg/b/bom.go"); got != "\xEF\xBB\xBF// SPDX-License-Identifier: MIT\n\npackage b\n" {
		t.Fatalf("BOM must stay first: %q", got)
	}
	for _, rel := range []string{"pkg/b/gen.go", "pkg/b/licensed.go", "pkg/b/testdata/x.go", "cmd/main.go", "pkg/b/notes.txt", "pkg/node_modules/m.go"} {
		if strings.Contains(readRel(t, root, rel), "MIT") {
			t.Errorf("%s must not change", rel)
		}
	}
	if !strings.Contains(res.Text, "changed 3 file(s)") || !strings.Contains(res.Text, "skipped by filter 2") {
		t.Fatalf("summary: %s", res.Text)
	}
	if len(res.ChangedPaths) != 3 {
		t.Fatalf("ChangedPaths = %v", res.ChangedPaths)
	}
	// Idempotent: a second run skips everything by the same filter.
	again := runEditFiles(t, root, map[string]any{
		"include": "pkg/**/*.go", "exclude": "**/testdata/**", "action": "prepend",
		"new": "// SPDX-License-Identifier: MIT\n\n", "skip_if_matches": `SPDX-License-Identifier|DO NOT EDIT`,
	})
	if !strings.Contains(again.Text, "changed 0 file(s)") || !strings.Contains(again.Text, "Nothing written") {
		t.Fatalf("second run: %s", again.Text)
	}
}

func TestEditFilesWordRenameReportsLeftovers(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"src/a.ts": "const userId = 1;\nuse(userId, userIdHash, x.userId);\n",
		"src/b.ts": "export function getUserId(userId: string) { return userId }\n",
		"src/c.ts": "nothing here\n",
	})
	res := runEditFiles(t, root, map[string]any{"include": "src/*.ts", "old": "userId", "new": "accountId", "word": true})
	if res.Err != nil {
		t.Fatal(res.Err)
	}
	if got := readRel(t, root, "src/a.ts"); got != "const accountId = 1;\nuse(accountId, userIdHash, x.accountId);\n" {
		t.Fatalf("a.ts: %q", got)
	}
	if got := readRel(t, root, "src/b.ts"); got != "export function getUserId(accountId: string) { return accountId }\n" {
		t.Fatalf("b.ts: %q", got)
	}
	if !strings.Contains(res.Text, "5 replacement(s)") || !strings.Contains(res.Text, "matches of old left in edited files: 0") || !strings.Contains(res.Text, "no match: src/c.ts") {
		t.Fatalf("summary: %s", res.Text)
	}
}

func TestEditFilesRegexAndDryRun(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"a.py": "import os\nVERSION = '1.0'\n",
		"b.py": "VERSION = '2.0'\n",
	})
	dry := runEditFiles(t, root, map[string]any{"include": "*.py", "old": `VERSION = '(\d)\.0'`, "new": "VERSION = '$1.1'", "regex": true, "dry_run": true})
	if dry.Err != nil || !strings.Contains(dry.Text, "would change 2 file(s)") || !strings.Contains(dry.Text, "+ VERSION = '1.1'") {
		t.Fatalf("dry run: %v %s", dry.Err, dry.Text)
	}
	if readRel(t, root, "a.py") != "import os\nVERSION = '1.0'\n" || len(dry.ChangedPaths) != 0 {
		t.Fatal("dry run wrote a file")
	}
	res := runEditFiles(t, root, map[string]any{"include": "*.py", "old": `VERSION = '(\d)\.0'`, "new": "VERSION = '$1.1'", "regex": true, "only_if_matches": "^import os$"})
	if res.Err != nil {
		t.Fatal(res.Err)
	}
	if readRel(t, root, "a.py") != "import os\nVERSION = '1.1'\n" || readRel(t, root, "b.py") != "VERSION = '2.0'\n" {
		t.Fatalf("regex/only filter wrong: %s", res.Text)
	}
}

func TestEditFilesArgumentErrors(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"x.txt": "a\n"})
	for name, args := range map[string]map[string]any{
		"no old":          {"include": "*.txt", "new": "b"},
		"bad action":      {"include": "*.txt", "new": "b", "action": "delete"},
		"regex and word":  {"include": "*.txt", "old": "a", "new": "b", "regex": true, "word": true},
		"bad glob":        {"include": "/abs/*.txt", "old": "a", "new": "b"},
		"bad skip regex":  {"include": "*.txt", "old": "a", "new": "b", "skip_if_matches": "("},
		"escape":          {"include": "*.txt", "old": "a", "new": "b", "path": "../.."},
		"prepend has old": {"include": "*.txt", "old": "a", "new": "b", "action": "prepend"},
	} {
		if res := runEditFiles(t, root, args); res.Err == nil {
			t.Errorf("%s: want error, got %s", name, res.Text)
		}
	}
	if readRel(t, root, "x.txt") != "a\n" {
		t.Fatal("an invalid call wrote")
	}
}

func TestEditFilesApprovalOnlyForMassEdit(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"a.txt": "x\n", "b.txt": "x\n", "c.txt": "x\n"})
	tool := &EditFiles{BaseDir: root, ApprovalThreshold: 2}
	args := json.RawMessage(`{"include":"*.txt","old":"x","new":"y"}`)
	req, err := tool.approval(context.Background(), args)
	if err != nil || req == nil {
		t.Fatalf("3 files over a threshold of 2 must ask: %v %v", req, err)
	}
	if req.Tool != "edit_files" || req.Operation != "mass_edit" || req.Count != 3 || !req.Reversible {
		t.Fatalf("request: %+v", req)
	}
	if req, _ := tool.approval(context.Background(), json.RawMessage(`{"include":"*.txt","old":"x","new":"y","dry_run":true}`)); req != nil {
		t.Fatal("a dry run never asks")
	}
	small := &EditFiles{BaseDir: root}
	if req, _ := small.approval(context.Background(), args); req != nil {
		t.Fatal("an ordinary workspace edit stays ungated like patch_file")
	}
	if spec := tool.Spec(); spec.Approval == nil || spec.ReadOnly {
		t.Fatal("edit_files must be a gated mutation")
	}
}
